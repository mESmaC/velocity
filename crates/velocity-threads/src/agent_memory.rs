//! Per-project agent memory directory keyed by project ID and seeded from the AIRC ledger (#539).

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use velocity_airc::{Channel, Entry};
use velocity_core::text_budget::preview;

const MEMORY_ROOT: &str = "agent-memory";
const MEMORY_FILE: &str = "MEMORY.md";
const LEDGER_SEED_FILE: &str = "ledger-seed.md";
const LEDGER_START: &str = "<!-- velocity:ledger-start -->";
const LEDGER_END: &str = "<!-- velocity:ledger-end -->";
const LEDGER_SEQ_PREFIX: &str = "<!-- velocity:ledger-seq:";
const LEDGER_SEQ_SUFFIX: &str = " -->";

const SUMMARY_DISCOVERIES: usize = 8;
const SUMMARY_PAST_WORK: usize = 6;
const SEED_DISCOVERIES: usize = 15;
const SEED_PAST_WORK: usize = 15;

/// Per-project memory folder under Velocity's app data directory.
/// Stable across thread workspaces so Claude and other agents share memory within a project.
pub fn project_memory_dir(app_data: &Path, project: u32) -> PathBuf {
    app_data.join(MEMORY_ROOT).join(project.to_string())
}

/// Ensures the project's memory folder exists and refreshes its managed AIRC ledger seed
/// without overwriting any agent-authored notes in `MEMORY.md`.
pub fn prepare_project_memory(app_data: &Path, project: u32) -> io::Result<PathBuf> {
    let dir = project_memory_dir(app_data, project);
    fs::create_dir_all(&dir)?;
    let (discoveries, past_work) = read_ledger_entries(app_data, project);
    sync_memory_files(&dir, &discoveries, &past_work)?;
    Ok(dir)
}

fn read_ledger_entries(app_data: &Path, project: u32) -> (Vec<Entry>, Vec<Entry>) {
    let Ok(channel) = Channel::open(app_data, &project.to_string()) else {
        return (Vec::new(), Vec::new());
    };
    let discoveries = channel.ledger("discovery", 0).unwrap_or_default();
    let past_work = channel.ledger("past_work", 0).unwrap_or_default();
    (discoveries, past_work)
}

/// Refreshes `ledger-seed.md` and the managed ledger section in `MEMORY.md` atomically.
pub(crate) fn sync_memory_files(
    dir: &Path,
    discoveries: &[Entry],
    past_work: &[Entry],
) -> io::Result<()> {
    let max_seq = discoveries
        .iter()
        .chain(past_work.iter())
        .map(|entry| entry.sequence)
        .max()
        .unwrap_or(0);
    let memory_path = dir.join(MEMORY_FILE);
    let seed_path = dir.join(LEDGER_SEED_FILE);
    let existing = match fs::read_to_string(&memory_path) {
        Ok(content) => Some(content),
        Err(error) if error.kind() == io::ErrorKind::NotFound => None,
        Err(error) => return Err(error),
    };
    if let Some(content) = &existing
        && seed_path.is_file()
        && recorded_sequence(content) == Some(max_seq)
    {
        return Ok(());
    }
    let seed_content = render_ledger_seed(discoveries, past_work, max_seq);
    write_atomic(&seed_path, seed_content.as_bytes())?;
    let managed = render_managed_block(discoveries, past_work, max_seq);
    let updated = merge_memory_document(existing.as_deref(), &managed);
    write_atomic(&memory_path, updated.as_bytes())?;
    Ok(())
}

fn recorded_sequence(content: &str) -> Option<u64> {
    let start = content.find(LEDGER_SEQ_PREFIX)? + LEDGER_SEQ_PREFIX.len();
    let end = content[start..].find(LEDGER_SEQ_SUFFIX)?;
    content[start..start + end].trim().parse().ok()
}

fn render_ledger_seed(discoveries: &[Entry], past_work: &[Entry], max_seq: u64) -> String {
    let mut out = format!(
        "# Project Ledger Seed\n\nGenerated by Velocity from the project's AIRC ledger (through seq {max_seq}).\n"
    );
    out.push_str("\n## Recent Discoveries\n");
    let recent_discoveries: Vec<&Entry> = discoveries.iter().rev().take(SEED_DISCOVERIES).collect();
    if recent_discoveries.is_empty() {
        out.push_str("- None recorded yet.\n");
    } else {
        for entry in recent_discoveries {
            let line = single_line(&entry.text, 400);
            out.push_str(&format!(
                "- [seq {} · {}] {line}\n",
                entry.sequence, entry.nick
            ));
        }
    }
    out.push_str("\n## Recent Past Work\n");
    let recent_work: Vec<&Entry> = past_work.iter().rev().take(SEED_PAST_WORK).collect();
    if recent_work.is_empty() {
        out.push_str("- None recorded yet.\n");
    } else {
        for entry in recent_work {
            let line = single_line(&entry.text, 240);
            out.push_str(&format!(
                "- [seq {} · {}] {line}\n",
                entry.sequence, entry.nick
            ));
        }
    }
    out
}

fn render_managed_block(discoveries: &[Entry], past_work: &[Entry], max_seq: u64) -> String {
    let mut out = format!(
        "{LEDGER_START}\n{LEDGER_SEQ_PREFIX}{max_seq}{LEDGER_SEQ_SUFFIX}\n## Seeded from AIRC Ledger\n\nSee [ledger-seed.md](ledger-seed.md) for fuller recent entries.\n"
    );
    let recent_discoveries: Vec<&Entry> =
        discoveries.iter().rev().take(SUMMARY_DISCOVERIES).collect();
    if !recent_discoveries.is_empty() {
        out.push_str("\n### Recent Discoveries\n");
        for entry in &recent_discoveries {
            let line = single_line(&entry.text, 180);
            out.push_str(&format!(
                "- [seq {} · {}] {line}\n",
                entry.sequence, entry.nick
            ));
        }
    }
    let recent_work: Vec<&Entry> = past_work.iter().rev().take(SUMMARY_PAST_WORK).collect();
    if !recent_work.is_empty() {
        out.push_str("\n### Recent Past Work\n");
        for entry in &recent_work {
            let line = single_line(&entry.text, 140);
            out.push_str(&format!(
                "- [seq {} · {}] {line}\n",
                entry.sequence, entry.nick
            ));
        }
    }
    if recent_discoveries.is_empty() && recent_work.is_empty() {
        out.push_str("\n- No AIRC ledger entries recorded yet.\n");
    }
    out.push_str(LEDGER_END);
    out
}

fn merge_memory_document(existing: Option<&str>, managed_block: &str) -> String {
    let Some(content) = existing.filter(|text| !text.trim().is_empty()) else {
        return format!(
            "# Project Memory\n\nShared across every thread and workspace in this project.\nAdd project-wide notes outside the Velocity ledger markers below.\n\n{managed_block}\n"
        );
    };
    if let Some(start) = content.find(LEDGER_START)
        && let Some(end_offset) = content[start..].find(LEDGER_END)
    {
        let end = start + end_offset + LEDGER_END.len();
        let mut merged = String::with_capacity(content.len() + managed_block.len());
        merged.push_str(&content[..start]);
        merged.push_str(managed_block);
        merged.push_str(&content[end..]);
        return merged;
    }
    let separator = if content.ends_with('\n') {
        "\n"
    } else {
        "\n\n"
    };
    format!("{content}{separator}{managed_block}\n")
}

fn single_line(text: &str, budget: usize) -> String {
    let collapsed = text.split_whitespace().collect::<Vec<_>>().join(" ");
    preview(&collapsed, budget)
}

fn write_atomic(path: &Path, bytes: &[u8]) -> io::Result<()> {
    let name = path
        .file_name()
        .and_then(|value| value.to_str())
        .unwrap_or("memory");
    let temp = path.with_file_name(format!(".{name}.{}.tmp", uuid::Uuid::new_v4()));
    fs::write(&temp, bytes)?;
    match fs::rename(&temp, path) {
        Ok(()) => Ok(()),
        Err(_) => {
            // Windows rename can fail when replacing an existing file opened by a reader.
            let result = fs::write(path, bytes);
            let _ = fs::remove_file(&temp);
            result
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_entry(sequence: u64, kind: &str, nick: &str, text: &str) -> Entry {
        Entry {
            sequence,
            session: None,
            time: "2026-11-20T00:00:00Z".into(),
            kind: kind.into(),
            nick: nick.into(),
            member: "thread-1".into(),
            text: text.into(),
            to: Vec::new(),
            intent: None,
            pull_request: None,
            head: None,
            claim: None,
            dependency: None,
            checkout: None,
            message_mode: None,
            acknowledged: None,
            files: Vec::new(),
            velocity_issue: None,
            rosen_issue: None,
            task_change: None,
            change: None,
            payload: None,
        }
    }

    // Risk (#539): seeding per-project agent memory from the AIRC ledger must populate
    // MEMORY.md and ledger-seed.md while preserving agent-authored memory across refreshes.
    #[test]
    fn seeds_from_ledger_and_preserves_agent_notes_across_refreshes()
    -> Result<(), Box<dyn std::error::Error>> {
        let dir = std::env::temp_dir().join(format!(
            "velocity-agent-memory-test-{}",
            uuid::Uuid::new_v4()
        ));
        fs::create_dir_all(&dir)?;
        let initial_discoveries = vec![sample_entry(
            10,
            "discovery",
            "issue-511",
            "Touch edited crate files if shared cargo target skips recheck.",
        )];
        let initial_work = vec![sample_entry(
            12,
            "past_work",
            "issue-537",
            "Landed preflight tool on velocity-run.",
        )];
        sync_memory_files(&dir, &initial_discoveries, &initial_work)?;

        let memory_path = dir.join(MEMORY_FILE);
        let first = fs::read_to_string(&memory_path)?;
        assert!(first.contains("Touch edited crate files"));
        assert!(first.contains("Landed preflight tool"));
        assert!(dir.join(LEDGER_SEED_FILE).is_file());

        // Simulate an agent adding its own notes outside the managed block.
        let with_agent_note =
            format!("{first}\n## Agent Notes\n- Keep functions under 60 lines.\n");
        fs::write(&memory_path, &with_agent_note)?;

        let updated_discoveries = vec![
            initial_discoveries[0].clone(),
            sample_entry(25, "discovery", "issue-539", "New ledger discovery."),
        ];
        sync_memory_files(&dir, &updated_discoveries, &initial_work)?;

        let refreshed = fs::read_to_string(&memory_path)?;
        assert!(refreshed.contains("New ledger discovery."));
        assert!(refreshed.contains("## Agent Notes\n- Keep functions under 60 lines."));
        assert_eq!(recorded_sequence(&refreshed), Some(25));

        let _ = fs::remove_dir_all(&dir);
        Ok(())
    }
}
